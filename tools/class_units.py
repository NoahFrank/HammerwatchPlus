"""class_units.py - point base-game units at our script classes.

info.xml `classmaps` look like the way to swap a unit behaviour (or a class a
unit names for InstantiateClass) for a subclass, but the engine ignores them
for both (checked in game, 2026-10-17: a produced vanilla pet stayed
MiniPetFlying with `MiniPetFlying -> HWPMiniPetFlying` mapped, packed or
unpacked). So a module lists the swaps in its module.json:

    "class_swaps": {"Chest": "HWPChest"}

and this tool copies every base unit that uses one of those classes
(`<behavior class="X"` or `<string name="class">X</string>`) into the module
with our class in its place. The copies shadow the base units: build.py treats
them as declared overrides ("generated", no .orig needed, since they are remade
from gamecode/sdk/hoh2/ on every build) and keeps them out of git (a marked block in the
module's .gitignore), because they are made from the player's own install.

    python tools/class_units.py          # every module with class_swaps
    python tools/class_units.py keys     # only these
    python tools/class_units.py --list   # print the units, write nothing
"""
import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import gamepaths as paths  # noqa: E402

GENERATED = "<!-- GENERATED by tools/class_units.py"
IGNORE_BEGIN = "# >>> tools/class_units.py (generated from the HoH2 base; do not edit)"
IGNORE_END = "# <<< tools/class_units.py"


def class_re(swaps: dict) -> re.Pattern:
    names = "|".join(re.escape(k) for k in sorted(swaps))
    return re.compile(r'(<behavior class="|<string name="class">)(' + names + r')(?=["<])')


def swap(text: str, swaps: dict) -> str:
    return class_re(swaps).sub(lambda m: m.group(1) + swaps[m.group(2)], text)


def units_for(swaps: dict) -> list[str]:
    """base units (relative paths) that use one of the swapped classes"""
    if not swaps:
        return []
    rx = class_re(swaps)
    out = []
    for p in sorted(paths.BASE_HOH2.rglob("*.unit")):
        if rx.search(p.read_text(encoding="utf-8", errors="replace")):
            out.append(p.relative_to(paths.BASE_HOH2).as_posix())
    return out


def write_ignore(mod_dir: Path, rels: list[str]) -> None:
    gi = mod_dir / ".gitignore"
    text = gi.read_text(encoding="utf-8") if gi.is_file() else ""
    a, b = text.find(IGNORE_BEGIN), text.find(IGNORE_END)
    if a >= 0 and b > a:
        text = text[:a] + text[b + len(IGNORE_END):].lstrip("\n")
    block = "\n".join([IGNORE_BEGIN] + ["/" + r for r in rels] + [IGNORE_END]) + "\n"
    text = (text.rstrip("\n") + "\n" if text.strip() else "") + block
    with open(gi, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def generate(cfg: dict, write: bool = True) -> list[str]:
    """write the module's class-swapped units; returns their relative paths"""
    swaps = cfg.get("class_swaps") or {}
    rels = units_for(swaps)
    if not write:
        return rels
    for rel in rels:
        src = (paths.BASE_HOH2 / rel).read_text(encoding="utf-8", errors="replace")
        out = cfg["dir"] / rel
        out.parent.mkdir(parents=True, exist_ok=True)
        with open(out, "w", encoding="utf-8", newline="\n") as f:
            f.write(f"{GENERATED} from the base unit, with our script class -->\n" + swap(src, swaps))
    if swaps:
        write_ignore(cfg["dir"], rels)
    return rels


def main(argv=None) -> None:
    import build
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("modules", nargs="*")
    ap.add_argument("--list", action="store_true", help="print the units, write nothing")
    args = ap.parse_args(argv)
    if not paths.BASE_HOH2.is_dir():
        sys.exit("run tools/bootstrap.py first (gamecode/sdk/hoh2/ missing)")
    for cfg in [build.load_module(d) for d in paths.module_dirs()]:
        if args.modules and cfg["id"] not in args.modules:
            continue
        if not cfg.get("class_swaps"):
            continue
        rels = generate(cfg, write=not args.list)
        print(f"{cfg['id']}: {len(rels)} unit(s) -> {', '.join(f'{k}->{v}' for k, v in cfg['class_swaps'].items())}")
        if args.list:
            for r in rels:
                print("   ", r)


if __name__ == "__main__":
    main()
